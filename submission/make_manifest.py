"""Write the figure manifest: each published image with its hash, size, claim, data and code.

    python submission/make_manifest.py   # → submission/FIGURE_MANIFEST.md, submission/manifest.json
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
CODE = "submission/make_figures.py"
FIGS = {
    "01_cloud2grid_overview.png": dict(
        claim="Real clouds → solar power → a real grid → GENCO, on the 15 June 2024 clearing; each layer labelled with its provenance.",
        data="data/demo/events/jun15_cloud_clearing/ (E-View frames 09:00 and 11:30 UTC, fleet_pv.parquet, summary.parquet, AC branch states), data/demo/network_layout.json",
        code=f"{CODE} fig1",
    ),
    "02_transfer_learning_journey.png": dict(
        claim="Five pre-registered stages, each fixing one limitation and exposing the next; real-state PBE and PV response per stage.",
        data="reports/tables/e5d_real_transfer.csv, reports/tables/e4_family_summary.csv (S0), reports/e5_topology_adaptation.md §1, reports/e5b_real_transfer.md",
        code=f"{CODE} fig2",
    ),
    "03_pv_response_real_states.png": dict(
        claim="On 2,829 real states the PV-to-import slope is −0.04 (E5c) and −1.07 (E5d) against AC −1.02; calibration incomplete (+13.1 MW, E5D-D).",
        data="data/demo/pv_response_s1.parquet (partial residuals of the published S1 regression), data/demo/catalog.json, reports/tables/e5d_real_transfer.csv",
        code=f"{CODE} fig3",
    ),
    "04_real_transfer_performance.png": dict(
        claim="Different stages fix different things: E5b lowest PBE, E5c best import spread, E5d only physical PV sensitivity; no stage passes the full gate.",
        data="reports/tables/e5d_real_transfer.csv; gate lines from configs/experiments/e5d_selection.yaml",
        code=f"{CODE} fig4",
    ),
    "05_explorer_hero_event.png": dict(
        claim="The deployed Explorer: guided tour (slide 6 of 6), Overview, Scientific story. Screenshots only; no data drawn.",
        data="submission/screenshots/explorer_guided_tour_slide6.png, explorer_overview_top.png, explorer_story_steps.png (captured 16 Oct 2026 from the Explorer at publication commit 41ab219, light theme, 1440 px viewport at 2× density)",
        code=f"{CODE} fig5",
    ),
    "06_why_response_is_not_enough.png": dict(
        claim="Post-hoc E6 diagnostic (held-out synthetic only): import compressed toward the training mean; the level error is shared within PV pairs and cancels in the supervised change.",
        data="reports/tables/e6_import_states_e5d.csv, e6_pv_pairs_e5d.csv, e6_pair_level_cancellation.csv, e6_model_comparison.csv; reports/experiments/e6_feasibility/diagnostic.json",
        code=f"{CODE} fig6",
    ),
}


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> None:
    rows, js = [], {"figures": {}, "screenshots": {}}
    for name, meta in FIGS.items():
        p = HERE / "figures" / name
        w, h = Image.open(p).size
        js["figures"][name] = dict(sha256=sha(p), bytes=p.stat().st_size, px=[w, h], **meta)
        rows.append(
            f"### `{name}`\n\n- **Claim:** {meta['claim']}\n- **Data:** {meta['data']}\n"
            f"- **Code:** `{meta['code']}`\n- **File:** {w}×{h} px, {p.stat().st_size / 1e6:.2f} MB, "
            f"SHA256 `{sha(p)}`\n"
        )
    for p in sorted((HERE / "screenshots").glob("*.png")):
        js["screenshots"][p.name] = dict(sha256=sha(p), px=list(Image.open(p).size))
    shots = "\n".join(
        f"| `{n}` | {d['px'][0]}×{d['px'][1]} | `{d['sha256'][:16]}…` |" for n, d in js["screenshots"].items()
    )
    (HERE / "manifest.json").write_text(json.dumps(js, indent=2) + "\n")
    (HERE / "FIGURE_MANIFEST.md").write_text(
        "# Figure manifest\n\n"
        "Every image in the Cloud2Grid write-up, with the claim it supports, its frozen inputs, the code that\n"
        "draws it and its hash. Generated by `submission/make_manifest.py`; machine-readable copy in\n"
        "`manifest.json`. Value-level sources for every annotation are in [`FIGURE_SOURCES.md`](FIGURE_SOURCES.md),\n"
        "and every number quoted in the text is re-checked by `submission/check_post.py`.\n\n"
        "Rebuild: `C2G_FONT_DIR=<static Source Sans TTFs> uv run python submission/make_figures.py [1-6]`.\n\n"
        + "\n".join(rows)
        + "\n## Explorer screenshots (inputs of figure 5)\n\n| File | Pixels | SHA256 |\n|---|---|---|\n"
        + shots
        + "\n"
    )
    print("wrote FIGURE_MANIFEST.md and manifest.json")


if __name__ == "__main__":
    main()
