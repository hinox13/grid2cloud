PAIRS_PER_TYPE = 8


def lam_tag(lam: float) -> str:
    return f"{lam:g}"


def run_name(lam: float, seed: int) -> str:
    return f"e5d_l{lam_tag(lam)}_s{seed}"


def runs_spec() -> list[tuple[float, int, str]]:
    """(λ, seed, role) — the six pre-registered runs, primary first."""
    r = CFG["runs"]
    out = [(float(r["primary"]["lambda"]), s, "primary") for s in r["primary"]["seeds"]]
    out += [
        (float(lam), s, "sensitivity")
        for lam in r["sensitivity"]["lambda"]
        for s in r["sensitivity"]["seeds"]
    ]
    c = r["control_code_path"]
    out += [(float(c["lambda"]), s, "control") for s in c["seeds"]]
    return out


def e5c_split_dir(seed: int) -> Path:
    return E5C_WORK / "splits" / e5c.run_name(N_TRAIN, seed)


def assert_e5c_splits(seed: int) -> dict[str, str]:
    """The E5d absolute splits ARE the E5c n10000 split files of the same seed (hash-checked)."""
    rec = json.loads(
        (
            REPO_ROOT / "reports/experiments/e5c/runs" / f"{e5c.run_name(N_TRAIN, seed)}.json"
        ).read_text()
    )
    d = e5c_split_dir(seed)
    import torch

    got = {
        k: sha256_ids(sorted(torch.load(d / f"{k}.pt").tolist())) for k in ("train", "val", "test")
    }
    if got != rec["split_sha256"]:
        raise LeakageError(
            f"E5c n{N_TRAIN} s{seed} split files changed: {got} vs {rec['split_sha256']}"
        )
    return got


def assert_pair_set(root: Path) -> pd.DataFrame:
    """A response pair set: under data/interim/e5d/pairs, E5d manifest, no weather columns."""
    root = Path(root).resolve()
    if root not in {p.resolve() for p in PAIR_ROOT.values()}:
        raise LeakageError(f"E5d pairs must be one of {list(PAIR_ROOT.values())}, got {root}")
    if any(f in str(root) for f in REAL_FAMILIES) or "/e4/" in str(root):
        raise LeakageError(f"E4 / real family path in pair data: {root}")
    man_path = root / "pairs.parquet"
    if not man_path.exists():
        raise LeakageError(f"no pair manifest at {man_path}")
    man = pd.read_parquet(man_path)
    if not (man["source"] == PAIR_SOURCE_TAG).all():
        raise LeakageError("pair manifest contains states not generated by the E5d pair builder")
    for t in ("bus_data", "branch_data", "gen_data"):
        p = root / NETWORK / "raw" / f"{t}.parquet"
        if p.exists():
            bad = set(pq_columns(p)) & set(WEATHER_COLUMNS)
            if bad:
                raise LeakageError(f"weather columns {bad} in {t}")
    return man


def complete_pairs(man: pd.DataFrame) -> pd.DataFrame:
    """One row per complete pair: probe_id, probe_type, magnitude_class, x_mw, scenario_a/b."""
    m = man[man.complete]
    a = m[m.member == "A"].set_index("probe_id")
    b = m[m.member == "B"].set_index("probe_id").reindex(a.index)
    return pd.DataFrame(
        {
            "probe_type": a.probe_type,
            "magnitude_class": a.magnitude_class,
            "x_mw": a.x_mw,
            "base_hash": a.base_hash,
            "scenario_a": a.scenario.astype(int),
            "scenario_b": b.scenario.astype(int),
        }
    ).reset_index()
