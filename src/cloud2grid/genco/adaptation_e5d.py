PAIR_SETS = ("train", "validation", "test")
PAIR_ROOT = {s: WORK / "pairs" / s for s in PAIR_SETS}
PAIR_SOURCE_TAG = "e5d-response-pairs (E5c envelope, E1 planning case, AC paired)"
GEN_BUSES, PMAX = e5c.GEN_BUSES, e5c.PMAX
REAL_FAMILIES = e5c.REAL_FAMILIES
N_TRAIN = int(CFG["runs"]["n_train"])
KAPPA = float(CFG["response_loss"]["kappa"]["value"])
HUBER_DELTA = 0.1
